// Whether a point is inside one of the outlines (ray casting): lets a test, or a caller, tell the rough land from the sea
inline bool worldLandAt(double latDeg, double lonDeg) {
    for (const auto& poly : worldOutline()) {
        bool in = false;
        const size_t n = poly.size();
        for (size_t i = 0, j = n - 1; i < n; j = i++) {
            const double xi = poly[i].first, yi = poly[i].second, xj = poly[j].first, yj = poly[j].second;
            if ((yi > latDeg) != (yj > latDeg) && lonDeg < (xj - xi) * (latDeg - yi) / (yj - yi) + xi) in = !in;
        }
        if (in) return true;
    }
    return false;
}

