const std::vector<cf32>& signallingConstellation(Nuc kind) {
    static const std::vector<cf32> qpsk = [] {
        const float s = 0.70710678f;   // Table C.1.1: 00 (1+j), 01 (-1+j), 10 (1-j), 11 (-1-j), over sqrt 2
        return std::vector<cf32>{cf32(s, s), cf32(-s, s), cf32(s, -s), cf32(-s, -s)};
    }();
    static const std::vector<cf32> n16 = build(k16_8, 4);
    static const std::vector<cf32> n64 = build(k64_9, 16);
    static const std::vector<cf32> n256a = build(k256_9, 64);
    static const std::vector<cf32> n256b = build(k256_13, 64);
    switch (kind) {
    case Nuc::Qpsk: return qpsk;
    case Nuc::Nuc16_8: return n16;
    case Nuc::Nuc64_9: return n64;
    case Nuc::Nuc256_9: return n256a;
    default: return n256b;
    }
}

