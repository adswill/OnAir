std::vector<cf32> build(const float* w, int b) {
    std::vector<cf32> x(4 * b);
    for (int i = 0; i < b; i++) {
        cf32 v(w[2 * i], w[2 * i + 1]);
        x[i] = v;
        x[b + i] = -std::conj(v);
        x[2 * b + i] = std::conj(v);
        x[3 * b + i] = -v;
    }
    return x;
}
