std::string lbjLocomotive(const std::string& raw) {
    if (raw.size() != 8 || raw.find_first_not_of("0123456789") != std::string::npos) return {};
    const std::string code = raw.substr(0, 4);
    // Only explicit four-digit subtypes use the whole field. A leading zero
    // must not turn an unknown four-digit code into a three-digit base type.
    const unsigned numeric = (unsigned)std::atoi(code.c_str());
    auto model = numeric >= 1000 ? locomotiveModel(numeric) : std::string();
    if (model.empty() && code.back() == '0') model = locomotiveModel((unsigned)std::atoi(code.substr(0, 3).c_str()));
    return (model.empty() ? code : model) + "-" + raw.substr(4);
}
