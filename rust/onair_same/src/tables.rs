//! The SAME / EAS lookup tables: originators, event codes, partial-county digits, US and Canadian location regions (47 CFR 11.31 (d), (e);
//! FIPS PUB 5-2 for the state codes; Statistics Canada codes for the provinces). Names are NUL-terminated so the C ABI can hand out pointers.

/// An originator or event: code, plain-English name (NUL-terminated), kind (NUL-terminated, "" when none).
pub struct Named {
    pub code: &'static str,
    pub name: &'static str,
    pub kind: &'static str,
}

/// A state / province / marine area: code, abbreviation ("" for marine areas), name, centre (0, 0 = no centre claimed). All NUL-terminated.
pub struct Region {
    pub fips: i32,
    pub abbr: &'static str,
    pub name: &'static str,
    pub lat: f64,
    pub lon: f64,
}

