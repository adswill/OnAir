// QRSS and DFCW grabber on simulated signals: element length 1 .. 60 s found automatically, text, centre found automatically, tone drift, noise sweep,
// noise alone, DFCW with both frequency orders. Simulated only: no recording of a real QRSS or DFCW signal was available.
#include "dect2/hamsci/hamsci_dsp.h"
#include "hamsci_testutil.h"
#include "../common/test_long.h"
using namespace dect2::hamsci;

static QrssGrabber* run(std::vector<float>& x, double fs, bool dfcw, QrssGrabber* g) {
    for (size_t i = 0; i < x.size(); i += 4800) g->feed(x.data() + i, std::min<size_t>(4800, x.size() - i));
    (void)dfcw;
    return g;
}

int main() {
    const double fs = 12000;
    // quick run: DFCW at 6 s elements only in the reversed case, the noise sweep at its two checked SNRs with one seed; ONAIR_TEST_LONG=1 runs it all
    const bool L = testLong();
    // element lengths: the text must be read and the length found
    for (double dot : {3.0, 6.0}) {
        for (bool dfcw : {false, true}) {
            if (!L && dfcw && dot > 3) continue;
            const std::string msg = "CQ DE LY2ABC";
            auto x = qrssGenerate(msg, dot, fs, 1234.5, dfcw, 2.0 / std::max(1.0, dot / 3.0) + 0.5, 0.3, 20.0);
            addNoiseSnr(x, fs, 6, 2500, 3, 0.3 * 0.3 / 2 * 0.4);
            // pad with quiet so the last letters are inside the analysed record
            auto tail = noiseOnly((size_t)(std::max(40.0, 12 * dot) * fs), 0.01, 7);
            x.insert(x.end(), tail.begin(), tail.end());
            QrssGrabber g(fs, dfcw);
            run(x, fs, dfcw, &g);
            const auto& st = g.state();
            CHECK(st.locked && std::fabs(st.centreHz - 1234.5) < 3.5, "%s dot %.0f: centre %.2f locked %d", dfcw ? "DFCW" : "QRSS", dot, st.centreHz, st.locked);
            CHECK(std::fabs(st.dotSec - dot) < 0.12 * dot + 0.1, "%s dot %.0f: element found %.1f s", dfcw ? "DFCW" : "QRSS", dot, st.dotSec);
            CHECK(st.text == msg, "%s dot %.0f: text '%s'", dfcw ? "DFCW" : "QRSS", dot, st.text.c_str());
        }
    }
    // reversed DFCW order
    {
        auto x = qrssGenerate("TEST", 6.0, fs, 900, true, -1.5, 0.3, 15.0);   // negative shift: dashes lower
        auto tail = noiseOnly((size_t)(60 * fs), 0.0, 7);
        x.insert(x.end(), tail.begin(), tail.end());
        addNoiseSnr(x, fs, 6, 2500, 4, 0.3 * 0.3 / 2 * 0.3);
        QrssGrabber g(fs, true);
        g.setDfcwReverse(true);
        run(x, fs, true, &g);
        CHECK(g.state().text == "TEST", "DFCW with dash below the dot: '%s' dot %.1f", g.state().text.c_str(), g.state().dotSec);
    }
    // noise sweep for QRSS3
    {
        const double snrs[] = {10, 0, -6, -12};
        int ok[4] = {};
        const int nSnr = L ? 4 : 2;            // -6 and -12 dB are only reported
        const uint32_t seeds = L ? 2 : 1;
        for (int si = 0; si < nSnr; si++)
            for (uint32_t seed = 1; seed <= seeds; seed++) {
                auto x = qrssGenerate("LY2ABC", 3.0, fs, 1500, false, 0, 0.5, 20.0);
                addNoiseSnr(x, fs, snrs[si], 2500, seed, 0.5 * 0.5 / 2 * 0.45);
                auto tail = noiseOnly((size_t)(45 * fs), 0.0, 7);
                x.insert(x.end(), tail.begin(), tail.end());
                QrssGrabber g(fs, false);
                g.setCentreHz(1500);
                run(x, fs, false, &g);
                if (g.state().text == "LY2ABC") ok[si]++;
            }
        std::printf("QRSS3 noise sweep (SNR in 2500 Hz, exact text of %u):", seeds);
        for (int i = 0; i < nSnr; i++) std::printf(" %+.0f dB: %d", snrs[i], ok[i]);
        std::printf("\n");
        CHECK(ok[0] == (int)seeds && ok[1] == (int)seeds, "strong signals %d %d", ok[0], ok[1]);
    }
    // drift of the tone: 0.02 Hz / s over the record (generated by a keyed carrier whose frequency ramps)
    {
        auto base = qrssGenerate("CQ", 3.0, fs, 1000, false, 0, 0.3, 20.0);
        // the envelope of the keyed carrier (a 5 % ramped on/off) is rebuilt from a generated 1 kHz tone: multiply the ramped tone by a phase rotation
        std::vector<float> y(base.size());
        for (size_t i = 0; i < base.size(); i++) {
            const double t = (double)i / fs;
            const size_t j = i >= 3 ? i - 3 : 0;               // 1000 Hz at 12 kHz: 3 samples are a quarter cycle
            const double add = 2 * 3.14159265358979 * 0.01 * t * t;   // the integral of the 0.02 Hz / s ramp, in cycles
            y[i] = (float)(base[i] * std::cos(add) + base[j] * std::sin(add));
        }
        auto tail = noiseOnly((size_t)(40 * fs), 0.0, 7);
        y.insert(y.end(), tail.begin(), tail.end());
        addNoiseSnr(y, fs, 6, 2500, 9, 0.3 * 0.3 / 2 * 0.3);
        QrssGrabber g(fs, false);
        g.setCentreHz(1000);
        run(y, fs, false, &g);
        CHECK(g.state().text == "CQ", "drifting tone: '%s' dot %.1f locked %d", g.state().text.c_str(), g.state().dotSec, g.state().locked);
    }
    // noise alone: no text, no lock to a "signal" that is not there
    {
        auto x = noiseOnly((size_t)(120 * fs), 0.1, 5);
        QrssGrabber g(fs, false);
        run(x, fs, false, &g);
        CHECK(g.state().text.empty(), "noise alone gave text '%s'", g.state().text.c_str());
    }
    std::printf(g_fails ? "QRSS/DFCW: %d failures\n" : "QRSS/DFCW: all passed\n", g_fails);
    return g_fails ? 1 : 0;
}
