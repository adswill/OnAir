"""Writes kaal_golden_codec.h: golden vectors from the reference kaal_codec.py (path: argv[1], default /tmp/kaal-codec).
Signal: 1 s, 16 kHz, 6000*sin(2 pi 440 t) + 3000*sin(2 pi 1250 t), truncated to int16 (no RNG).
Golden: the first 10 frames' bits (hex), the Python decode of them, and the Python decode of the same frames with
frame 5 all ones (reserved type, concealed) and frame 8 replaced by 7 zeros (wrong shape, concealed)."""
import sys, numpy as np
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "/tmp/kaal-codec")
import kaal_codec as kc

i = np.arange(16000)
x = (6000.0 * np.sin(2.0 * np.pi * 440.0 * i / 16000.0) + 3000.0 * np.sin(2.0 * np.pi * 1250.0 * i / 16000.0)).astype(np.int16)
fr = kc.encode(x)
NF = 10
good = fr[:NF]
y1 = kc.decode(good)
dmg = [r.copy() for r in good]
dmg[5] = np.ones(320, np.uint8)
dmg[8] = np.zeros(7, np.uint8)
y2 = kc.decode(dmg)

def hexrow(r):
    b = "".join(str(int(v)) for v in r)
    return format(int(b, 2), "080x")

with open("kaal_golden_codec.h", "w") as f:
    f.write("// Generated by gen_golden_codec.py from kaal_codec.py. Do not edit.\n#pragma once\n#include <cstdint>\n")
    f.write("static const int kGoldFrames = %d;\n" % NF)
    f.write("static const char* const kGoldBitsHex[%d] = {\n" % NF)
    for r in good:
        f.write('    "%s",\n' % hexrow(r))
    f.write("};\n")
    for name, y in (("kGoldPcmGood", y1), ("kGoldPcmDamaged", y2)):
        f.write("static const int16_t %s[%d] = {" % (name, len(y)))
        for k, v in enumerate(y):
            f.write(("\n    " if k % 16 == 0 else " ") + "%d," % int(v))
        f.write("\n};\n")
print("frames total", len(fr), "wrote", NF)
