"""Writes tests/kaal/kaal_golden.h from the Python prototype (tests/kaal/proto, same as /tmp/kaal-phy).
Run: python3 tests/kaal/gen_golden.py > tests/kaal/kaal_golden.h"""
import os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "proto"))
import kaal_phy as P
import kaal_fec as F

def xs_bits(seed, n):
    st = seed; out = []
    for _ in range(n):
        st, v = P._xorshift64(st); out.append((v >> 40) & 1)
    return out

def hexbits(b):  # MSB first
    b = list(b) + [0] * (-len(b) % 8)
    return "".join("%02x" % sum(b[i + k] << (7 - k) for k in range(8)) for i in range(0, len(b), 8))

msg = xs_bits(0x1234, 320)
cw = F.encode_frames(np.array(msg).reshape(1, -1))[0]
conv = P.conv_encode(msg[:64])
qbits = xs_bits(0x77, 64)
syms = P.qam16_map(qbits) * np.sqrt(10)
lv = [(int(round(s.real)), int(round(s.imag))) for s in syms]
# noisy symbols for the soft demap, from the portable generator
st = 0x99; noisy = []
for _ in range(8):
    st, a = P._xorshift64(st); st, b = P._xorshift64(st)
    noisy.append((((a >> 11) % 8000) / 1000.0 - 4.0, ((b >> 11) % 8000) / 1000.0 - 4.0))
nv = 0.1
ns = np.array([complex(a, b) for a, b in noisy]) / np.sqrt(10)
llr = P.qam16_demap_soft(ns, nv)
# decode test: hard LLR +-4 with 24 flipped positions chosen portably
st = 0xBEEF; flips = []
while len(flips) < 24:
    st, v = P._xorshift64(st); p = v % 640
    if p not in flips: flips.append(int(p))
r = np.where(cw == 0, 4.0, -4.0).astype(np.float32)
for p in flips: r[p] = -r[p]
dec, ok = F.decode_frames(r[None, :])
assert ok[0] and list(dec[0]) == msg, "python decode failed"
perm = P.interleave_perm(2560)
rrc = P.rrc_taps()
sw = P.sweep_template(48000)

o = []
o.append("// Generated by tests/kaal/gen_golden.py from the Python prototype. Do not edit.")
o.append("#pragma once\n#include <cstdint>")
o.append("static const char* const G_MSG_HEX = \"%s\";" % hexbits(msg))
o.append("static const char* const G_CODEWORD_HEX = \"%s\";" % hexbits(cw))
o.append("static const char* const G_CONV_HEX = \"%s\";   // conv_encode of the first 64 message bits" % hexbits(conv))
o.append("static const char* const G_QBITS_HEX = \"%s\";   // 64 bits -> 16 symbols" % hexbits(qbits))
o.append("static const int G_QLEVELS[16][2] = {%s};   // I,Q levels x sqrt(10)" % ",".join("{%d,%d}" % t for t in lv))
o.append("static const double G_NOISY[8][2] = {%s};   // received symbols x sqrt(10)" % ",".join("{%.3f,%.3f}" % t for t in noisy))
o.append("static const double G_NOISE_VAR = %s;" % nv)
o.append("static const double G_LLR[32] = {%s};   // max-log, positive = bit 0" % ",".join("%.6f" % x for x in llr))
o.append("static const int G_FLIPS[24] = {%s};" % ",".join(map(str, flips)))
o.append("static const int G_RRC_N = %d;" % len(rrc))
o.append("static const double G_RRC_HEAD[8] = {%s};" % ",".join("%.9f" % x for x in rrc[:8]))
o.append("static const double G_RRC_MID = %.9f;" % rrc[len(rrc) // 2])
o.append("static const double G_SWEEP_IDX[4][3] = {%s};   // sample index, re, im of sweep_template(48000)" % ",".join("{%d,%.9f,%.9f}" % (i, sw[i].real, sw[i].imag) for i in (1, 1000, 12345, 40000)))
o.append("static const uint16_t G_PERM2560[2560] = {\n%s};" % ",\n".join(",".join(map(str, perm[i:i + 20])) for i in range(0, 2560, 20)))
print("\n".join(o))
