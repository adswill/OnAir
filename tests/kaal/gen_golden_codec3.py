"""Writes kaal_golden_codec3.h: golden vectors from the reference kaal_codec_v3.py (path: argv[1], default /tmp/kaal-codec).
Signal (also built in test_kaal_codec3.cpp): 1 s, 16 kHz, a modulated three-partial voice-like tone plus integer LCG noise, truncated to int16.
Per profile (12, 16, 24, 32 kbit/s): the first NF frames' bits (hex), the Python decode of them. For 16 kbit/s also the Python decode of
the same frames with frame 2 replaced by a 24 kbit/s frame (wrong profile, concealed) and frame 4 replaced by 7 zeros (wrong shape)."""
import sys, numpy as np
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "/tmp/kaal-codec")
import kaal_codec_v3 as kc

def signal():
    x = np.zeros(16000, np.int16)
    st = 12345
    for i in range(16000):
        t = i / 16000.0
        env = 0.6 + 0.4 * np.sin(2.0 * np.pi * 3.0 * t)
        st = (st * 1103515245 + 12345) & 0x7FFFFFFF
        nz = (st >> 16) % 1201 - 600
        v = env * (4000.0 * np.sin(2.0 * np.pi * 200.0 * t) + 2500.0 * np.sin(2.0 * np.pi * 600.0 * t)
                   + 1500.0 * np.sin(2.0 * np.pi * 2400.0 * t)) + nz
        x[i] = int(v)
    return x

NF = 6
x = signal()
with open("kaal_golden_codec3.h", "w") as f:
    f.write("// Generated by gen_golden_codec3.py from kaal_codec_v3.py. Do not edit.\n#pragma once\n#include <cstdint>\n")
    f.write("static const int kG3Frames = %d;\n" % NF)
    dmg_y = None
    for kb in (12, 16, 24, 32):
        fr = kc.encode(x, kb)
        good = fr[:NF]
        y = kc.decode(good, kb)
        f.write("static const char* const kG3Bits%d[%d] = {\n" % (kb, NF))
        nb = kb * 20
        for r in good:
            b = "".join(str(int(v)) for v in r)
            f.write('    "%s",\n' % format(int(b, 2), "0%dx" % (nb // 4)))
        f.write("};\n")
        f.write("static const int16_t kG3Pcm%d[%d] = {" % (kb, len(y)))
        for k, v in enumerate(y):
            f.write(("\n    " if k % 16 == 0 else " ") + "%d," % int(v))
        f.write("\n};\n")
        if kb == 16:
            other = kc.encode(x, 24)
            dmg = [r.copy() for r in good]
            dmg[2] = other[2].copy()
            dmg[4] = np.zeros(7, np.uint8)
            dmg_y = kc.decode(dmg, 16)
        print(kb, "frames total", len(fr))
    f.write("static const int16_t kG3PcmDamaged16[%d] = {" % len(dmg_y))
    for k, v in enumerate(dmg_y):
        f.write(("\n    " if k % 16 == 0 else " ") + "%d," % int(v))
    f.write("\n};\n")
