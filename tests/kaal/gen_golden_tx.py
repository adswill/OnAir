"""Writes kaal_golden_tx.h: golden samples from the Python transmitter (kaal_tx.py) and the beacon slice (kaal_beacon_slice.py).
Usage: gen_golden_tx.py [phy_dir=/tmp/kaal-phy] [codec_dir=/tmp/kaal-codec]
Signal: 1 s, 16 kHz, 8000*sin(2 pi 440 t) truncated to int16 (no RNG). The values are the unscaled Python output (unit-power
convention); the C++ transmitter multiplies by kTxGain and uses a fixed sweep level instead of the measured data power, so the
test compares with a small tolerance."""
import sys
import numpy as np
phy = sys.argv[1] if len(sys.argv) > 1 else "/tmp/kaal-phy"
cod = sys.argv[2] if len(sys.argv) > 2 else "/tmp/kaal-codec"
sys.path.insert(0, cod); sys.path.insert(0, phy)
import kaal_tx, kaal_beacon_slice as S, kaal_beacon_v2 as KB

i = np.arange(16000)
pcm = (8000.0 * np.sin(2.0 * np.pi * 440.0 * i / 16000.0)).astype(np.int16)
sig, info = kaal_tx.encode_stream_info(pcm)
LATER = [1000, 5000, 20000, 40000, 62000, len(sig) - 1]

F = dict(version=1, frame_type=1, callsign="LY2ABC", lat=54.687, lon=25.279, power_value=120, link_quality=0, grid="KO26ab")
BIO = "Hi, I am testing KAAL, a custom digital voice mode. Tell me what you hear."
assert len(BIO) == 74
bits = KB.encode_beacon(F, BIO)
hbits = KB.encode_beacon(dict(F, frame_type=0))
sl = S.beacon_slice_encode(F, BIO)
SL_LATER = [500, 3000, 20000, 100000, len(sl) - 1]

def hexbits(b):
    s = "".join(str(int(v)) for v in b)
    s += "0" * (-len(s) % 4)
    return "".join("%x" % int(s[k:k + 4], 2) for k in range(0, len(s), 4))

with open("kaal_golden_tx.h", "w") as f:
    f.write("// Generated by tests/kaal/gen_golden_tx.py from the Python transmitter. Do not edit.\n#pragma once\n#include <cstddef>\n")
    f.write("static const size_t G_TX_LEN = %d;\n" % len(sig))
    f.write("static const double G_TX_HEAD[8][2] = {%s};\n" % ",".join("{%.7f,%.7f}" % (v.real, v.imag) for v in sig[:8]))
    f.write("static const size_t G_TX_IDX[%d] = {%s};\n" % (len(LATER), ",".join(str(k) for k in LATER)))
    f.write("static const double G_TX_LATER[%d][2] = {%s};\n" % (len(LATER), ",".join("{%.7f,%.7f}" % (sig[k].real, sig[k].imag) for k in LATER)))
    f.write("static const char* const G_BEACON_FULL_HEX = \"%s\";   // %d bits\n" % (hexbits(bits), len(bits)))
    f.write("static const int G_BEACON_FULL_BITS = %d;\n" % len(bits))
    f.write("static const char* const G_BEACON_HDR_HEX = \"%s\";   // %d bits, frame type 0\n" % (hexbits(hbits), len(hbits)))
    f.write("static const size_t G_SLICE_LEN = %d;\n" % len(sl))
    f.write("static const double G_SLICE_HEAD[8][2] = {%s};\n" % ",".join("{%.7f,%.7f}" % (v.real, v.imag) for v in sl[:8]))
    f.write("static const size_t G_SLICE_IDX[%d] = {%s};\n" % (len(SL_LATER), ",".join(str(k) for k in SL_LATER)))
    f.write("static const double G_SLICE_LATER[%d][2] = {%s};\n" % (len(SL_LATER), ",".join("{%.7f,%.7f}" % (sl[k].real, sl[k].imag) for k in SL_LATER)))
print(len(sig), len(bits), len(hbits), len(sl))
