"""Writes core/src/kaal/kaal_codec3_tables.h: the trained initial probabilities of the KAAL codec v3 (INITS of kaal_codec_v3.py,
path argv[1], default /tmp/kaal-codec) as dense arrays per profile id (0 = 16, 1 = 24, 2 = 32, 3 = 12 kbit/s); 0 means 'no entry'."""
import sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "/tmp/kaal-codec")
import kaal_codec_v3 as kc

out = ["// Generated by tests/kaal/gen_codec3_tables.py from kaal_codec_v3.py (INITS, tables trained on 5 speech clips). Do not edit.",
       "#pragma once", "#include <cstdint>", "namespace dect2 { namespace kaal3 {",
       "struct InitTable { uint16_t ez[3], es[3], em[8], rz[8][4], rm[8][2][6]; };",
       "static const InitTable kInit[4] = {"]
for pid in range(4):
    t = kc.INITS[pid]
    ez = [t.get(("ez", i), 0) for i in range(3)]
    es = [t.get(("es", i), 0) for i in range(3)]
    em = [t.get(("em", i), 0) for i in range(8)]
    rz = [[t.get(("rz", r, c), 0) for c in range(4)] for r in range(8)]
    rm = [[[t.get(("rm", r, j, i), 0) for i in range(6)] for j in range(2)] for r in range(8)]
    def fl(a):
        if isinstance(a, list):
            return "{" + ",".join(fl(x) for x in a) + "}"
        return str(a)
    out.append("  {%s,%s,%s,%s,%s}," % (fl(ez), fl(es), fl(em), fl(rz), fl(rm)))
out.append("};")
out.append("} }")
open(sys.argv[2] if len(sys.argv) > 2 else "core/src/kaal/kaal_codec3_tables.h", "w").write("\n".join(out) + "\n")
print("ok")
