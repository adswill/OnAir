#!/usr/bin/env python3
"""Add SPDX licence + copyright comment lines at the top of OnAir-owned source files. Idempotent. Run at the code freeze.

  python3 tools/release/add_spdx.py --dry-run            # default: counts per directory and a few sample diffs, writes nothing
  python3 tools/release/add_spdx.py --apply              # edit the files in place (commit the result as one commit)
  python3 tools/release/add_spdx.py --selftest [N]       # prove the header does not change what the compiler sees (see below)
  python3 tools/release/add_spdx.py --apply --derived    # also files that need more than our holder line (see below)

What it writes (comment style per language), after a shebang / coding line, before include guards or code:

    // SPDX-License-Identifier: GPL-3.0-or-later
    // Copyright (C) 2026 Kristijonas Adomaitis and OnAir contributors

The licence comes from the REUSE.toml entry that covers the file (REUSE reads the "Copyright (C)" line as the file's own
copyright notice). Files with other holders (--derived) get SPDX-FileCopyrightText lines for every holder of their entry.
Files are skipped (and counted) when
  - they already contain SPDX-License-Identifier in the first 30 lines (idempotent),
  - they are vendored (third_party/), build output, node_modules, or generated (header says generated / do not edit, .inc),
  - the REUSE.toml entry that covers them names another holder or a non-OnAir licence set: files derived from other projects
    (DecSAT, nrsc5, etisnoop, ...) keep their notice and are listed under "other holder"; --derived adds the full SPDX block
    for them (all holders of the entry) above the existing notice: review that diff by hand before committing,
  - their first lines show a copyright notice of someone else,
  - THIRD_PARTY.md names them (or their directory) in "Where used" and its "How" column says the code or tables were
    copied, ported, translated, adapted, vendored or generated from the other project,
  - their header says the code was ported / adapted / translated / copied from elsewhere, or names another licence
    (LGPL, MIT, BSD, Apache, CC0, public domain): those keep their own notices and are reviewed by hand.
  python3 tools/release/add_spdx.py --check   # exit 1 when an OnAir-owned source file still has no header (lists them)
Only comments are added, so nothing compiles differently. --selftest checks that: it copies N sample .c/.cpp files, adds the
header to the copy and compares `-fsyntax-only` results (return code and error messages without line numbers) between the
original and the copy. Rust crates: run `cargo check` in each rust/* crate after --apply (on the laptop worker); a `//`
comment before `//!` / `#![...]` is accepted by rustc.
"""
import argparse, difflib, importlib.util, os, random, re, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('check_spdx', os.path.join(HERE, 'check_spdx.py'))
chk = importlib.util.module_from_spec(spec); spec.loader.exec_module(chk)
import tomllib

SLASH = {'.c', '.h', '.cpp', '.hpp', '.cc', '.cxx', '.hh', '.m', '.mm', '.metal', '.rs', '.js', '.mjs', '.glsl', '.hlsl',
         '.vert', '.frag', '.comp', '.kt', '.kts', '.java'}
HASH = {'.py', '.sh', '.cmake'}
HASH_NAMES = {'CMakeLists.txt'}
SKIP_PREFIX = ('third_party/', 'LICENSES/', 'docs/', 'scratchpad/', 'build/', 'node_modules/')
GENERATED = re.compile(r'^\s*(//!?|#|/\*+|\*)\s*(@generated|generated by|generated from|this file is generated|auto-?generated|do not edit)', re.I | re.M)
OTHER_HOLDER = re.compile(r'copyright|\(c\)\s*\d{4}|©', re.I)
OURS = re.compile(r'Kristijonas Adomaitis|OnAir contributors', re.I)
# a header that says the file came from elsewhere, or names another licence: keep its notice, never add ours
FOREIGN = re.compile(r'(?i)\b(ported from|adapted from|translated from|copied from|vendored|licen[cs]ed under|'
                     r'(?:LGPL|GPL-2\.0-only|MIT|BSD|Apache|CC0|ISC|Zlib|MPL)[- ](?:licen[cs]e|\d)|public domain)')
# THIRD_PARTY.md "How" column words meaning the code (not just the facts) came from the other project
TP_COPIED = re.compile(r'(?i)cop(y|ied)|port(ed)?\b|translat|adapt|vendor|generated from|bundled|included as|derived')

def style(path):
    base = os.path.basename(path)
    ext = os.path.splitext(base)[1].lower()
    if base in HASH_NAMES or ext in HASH:
        return '#'
    if ext in SLASH:
        return '//'
    return None

def load_annotations():
    cfg = tomllib.load(open('REUSE.toml', 'rb'))
    out = []
    for a in cfg['annotations']:
        paths = a['path'] if isinstance(a['path'], list) else [a['path']]
        cr = a['SPDX-FileCopyrightText']
        cr = cr if isinstance(cr, list) else [cr]
        out.append(([chk.glob_to_re(p) for p in paths], a['SPDX-License-Identifier'], cr))
    return out

def covering(ann, f):
    r = None
    for pats, lic, cr in ann:
        if any(p.match(f) for p in pats):
            r = (lic, cr)
    return r

def holder_text(cr):
    return re.sub(r'^(Copyright\s*(\(C\)|\(c\)|©)?\s*)', '', cr).strip()

def third_party_copied():
    """paths in THIRD_PARTY.md "Where used" of rows whose "How" says code or tables were copied/ported/translated"""
    out = []
    try:
        md = open('THIRD_PARTY.md', encoding='utf-8').read()
    except OSError:
        return out
    for line in md.splitlines():
        if not line.startswith('|'):
            continue
        cols = [c.strip() for c in line.strip('|').split('|')]
        if len(cols) < 5 or not TP_COPIED.search(cols[4]):
            continue
        for m in re.finditer(r'((?:core|app|rust|tests|tools|web|data|sdk|server|android|relay|firmware|packaging)/[\w./*{},-]+)', cols[3]):
            p = m.group(1).rstrip('.,;)')
            if '{' in p or '*' in p:
                out.append(re.compile('^' + re.escape(p).replace(r'\*', '[^/]*').replace(r'\{', '(?:').replace(r'\}', ')').replace(',', '|')))
            else:
                out.append(re.compile('^' + re.escape(p.rstrip('/')) + r'(?:$|/|\.)' if not re.search(r'\.\w+$', p) else '^' + re.escape(p) + '$'))
    return out

def make_header(c, lic, crs, ours=False):
    if ours:   # the holder line exactly as REUSE.toml writes it
        return '%s SPDX-License-Identifier: %s\n%s %s\n' % (c, lic, c, crs[0])
    return ''.join('%s SPDX-License-Identifier: %s\n' % (c, lic) if i == 0 else '' for i in range(1)) + \
        ''.join('%s SPDX-FileCopyrightText: %s\n' % (c, holder_text(x)) for x in crs)

def transform(text, c, header):
    """Return the new text, or None when nothing should change."""
    nl = '\r\n' if '\r\n' in text[:2000] else '\n'
    bom = ''
    if text.startswith('﻿'):
        bom, text = '﻿', text[1:]
    lines = text.split('\n')
    head30 = '\n'.join(lines[:30])
    if 'SPDX-License-Identifier' in head30:
        return None
    hdr = header.replace('\n', nl)
    i = 0
    keep = []
    if lines and lines[0].startswith('#!'):
        keep.append(lines[0]); i = 1
    if c == '#' and i < len(lines) and re.match(r'#.*(coding[:=]|vim?:|-\*-)', lines[i]):
        keep.append(lines[i]); i += 1
    rest = lines[i:]
    sep = '' if (rest and rest[0].strip() == '') else nl
    new = nl.join(keep) + (nl if keep else '') + hdr + (sep if rest else '') + '\n'.join(rest)
    # '\n'.join keeps any '\r' of the original lines; header lines use the file's own newline
    return bom + new

def candidates(derived):
    ann = load_annotations()
    tpc = third_party_copied()
    res, skipped = [], {}
    files = [l for l in subprocess.run(['git', 'ls-files'], capture_output=True, text=True).stdout.split('\n') if l]
    def skip(why, f):
        skipped.setdefault(why, []).append(f)
    for f in files:
        c = style(f)
        if c is None or not os.path.isfile(f):
            continue
        if f.startswith(SKIP_PREFIX) or '/node_modules/' in f or '/build/' in f:
            skip('vendored/build/docs', f); continue
        cov = covering(ann, f)
        if cov is None:
            skip('not covered by REUSE.toml', f); continue
        lic, crs = cov
        try:
            text = open(f, encoding='utf-8').read()
        except (UnicodeDecodeError, OSError):
            skip('not utf-8', f); continue
        if not text.strip():
            skip('empty', f); continue
        top = '\n'.join(text.split('\n')[:12])
        if GENERATED.search(top):
            skip('generated', f); continue
        if 'LicenseRef-Unknown' in lic:
            skip('licence unknown', f); continue
        only_ours = all(OURS.search(x) for x in crs) and len(crs) == 1
        if not only_ours and not derived:
            skip('other holder (use --derived)', f); continue
        if only_ours and OTHER_HOLDER.search(top) and not OURS.search(top):
            skip('file names another holder', f); continue
        if only_ours and any(p.match(f) for p in tpc):
            skip('THIRD_PARTY.md: copied/ported code', f); continue
        if only_ours and FOREIGN.search(text[:3000]):
            skip('header names another source or licence', f); continue
        new = transform(text, c, make_header(c, lic, crs, ours=only_ours))
        if new is None:
            skip('already has SPDX', f); continue
        res.append((f, text, new))
    return res, skipped

def selftest(n):
    cxx = shutil.which('clang++') or shutil.which('c++') or shutil.which('g++')
    if not cxx:
        sys.exit('no C++ compiler found')
    res, _ = candidates(False)
    pool = [r for r in res if r[0].endswith(('.cpp', '.c', '.h')) and r[0].startswith(('core/src', 'app', 'tools', 'tests'))]
    random.Random(1).shuffle(pool)
    incs = ['-I', 'core/include', '-I', 'core/src', '-I', 'app', '-I', 'third_party', '-I', 'third_party/imgui', '-I', 'third_party/sqlite',
            '-I', 'third_party/lua', '-I', 'sdk/include', '-I', '.']
    ok = diff = clean = 0
    tmp = tempfile.mkdtemp(prefix='spdxtest')
    norm = lambda s: re.sub(r':\d+:\d+', '', re.sub(re.escape(tmp), '', s))
    for f, old, new in pool[:n]:
        base = os.path.basename(f)
        lang = ['-x', 'c'] if f.endswith('.c') else ['-x', 'c++', '-std=c++20']
        outs = []
        for tag, text in (('a', old), ('b', new)):
            p = os.path.join(tmp, tag + '_' + base)
            open(p, 'w').write(text)
            r = subprocess.run([cxx, '-fsyntax-only', '-w', '-ferror-limit=5'] + lang + incs + ['-iquote', os.path.dirname(f), p],
                               capture_output=True, text=True)
            outs.append((r.returncode, norm(r.stderr.replace('a_' + base, base).replace('b_' + base, base))))
        if outs[0][0] == outs[1][0] and re.sub(r'\n.*\^~*\n?', '\n', outs[0][1]).count('error') == re.sub(r'\n.*\^~*\n?', '\n', outs[1][1]).count('error'):
            ok += 1
            clean += outs[0][0] == 0
        else:
            diff += 1
            print('DIFFERENT:', f)
    shutil.rmtree(tmp, ignore_errors=True)
    print('selftest: %d files compiled before and after, %d same result (%d of them compile cleanly), %d different' % (ok + diff, ok, clean, diff))
    sys.exit(1 if diff else 0)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--derived', action='store_true')
    ap.add_argument('--selftest', nargs='?', const=50, type=int)
    ap.add_argument('--samples', type=int, default=3)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--list-skipped', metavar='WHY', help='print every file skipped for a reason containing WHY')
    a = ap.parse_args()
    if a.check:
        res, _ = candidates(False)
        for f, _, _ in res[:60]:
            print('no SPDX header:', f)
        print('%d OnAir-owned source files without an SPDX header%s' % (len(res), ': run python3 tools/release/add_spdx.py --apply' if res else ''))
        sys.exit(1 if res else 0)
    if a.selftest:
        selftest(a.selftest)
    res, skipped = candidates(a.derived)
    per = {}
    for f, _, _ in res:
        k = f.split('/')[0] if '/' in f else '.'
        per[k] = per.get(k, 0) + 1
    print('%s: %d files get a header' % ('APPLY' if a.apply else 'DRY RUN', len(res)))
    for k in sorted(per):
        print('  %-40s %5d' % (k, per[k]))
    print('skipped:')
    for why, fl in sorted(skipped.items()):
        print('  %-38s %5d  e.g. %s' % (why, len(fl), fl[0]))
        if a.list_skipped and a.list_skipped in why:
            for x in fl:
                print('      ', x)
    if not a.apply:
        random.Random(7).shuffle(res)
        for f, old, new in res[:a.samples]:
            print(''.join(list(difflib.unified_diff(old.split('\n'), new.split('\n'), 'a/' + f, 'b/' + f, lineterm='', n=2))[:14] and
                          [l + '\n' for l in list(difflib.unified_diff(old.split('\n'), new.split('\n'), 'a/' + f, 'b/' + f, lineterm='', n=2))[:14]]))
        return
    for f, old, new in res:
        with open(f, 'w', encoding='utf-8', newline='') as fh:
            fh.write(new)
    print('wrote %d files; now run: python3 tools/release/check_spdx.py, build, ctest, cargo check in rust/*' % len(res))

if __name__ == '__main__':
    main()
