"""List the user-visible strings that are new since a release and say which catalogs still lack a translation.

  python3 tools/release/gen_i18n_new.py [--since v0.2.9] [--base pub/integ-30] [--out docs/I18N-NEW-STRINGS-3.0.md]

A string is "used" when it appears as tr("..."), trw("..."), N_("...") or Tr("...") in app/ (git grep at that ref).
A catalog (app/i18n/<code>.txt, "English<TAB>translation") lacks a string when the key is missing or the
translation equals the English key (minus tools/i18n_keep_english.txt). Nothing is translated here.
"""
import argparse, re, subprocess, os, collections

PAT = re.compile(r'\b(?:tr|trw|N_|Tr)\(\s*"((?:[^"\\]|\\.)*)"')

def git(*a):
    return subprocess.run(['git', *a], capture_output=True, text=True).stdout

def used(ref):
    out = git('grep', '-hoE', r'(tr|trw|N_|Tr)\(\s*"([^"\\]|\\.)*"', ref, '--', 'app')
    s = set()
    for line in out.splitlines():
        m = PAT.search(line)
        if m:
            s.add(m.group(1))
    return s

def catalogs(ref):
    cats = {}
    names = git('ls-tree', '--name-only', ref, 'app/i18n/').split()
    for n in names:
        if n.endswith('.txt'):
            d = {}
            for l in git('show', ref + ':' + n).splitlines():
                if l.startswith('#') or '\t' not in l:
                    continue
                k, v = l.split('\t', 1)
                d[k] = v
            cats[os.path.basename(n)[:-4]] = d
    return cats

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--since', default='v0.2.9')
    ap.add_argument('--base', default='pub/integ-30')
    ap.add_argument('--out', default='docs/I18N-NEW-STRINGS-3.0.md')
    a = ap.parse_args()
    old, new = used(a.since), used(a.base)
    added = sorted(new - old, key=lambda s: s.lower())
    cats = catalogs(a.base)
    keep = set(l.rstrip('\n') for l in open('tools/i18n_keep_english.txt')) if os.path.exists('tools/i18n_keep_english.txt') else set()
    lack = collections.Counter()
    rows = []
    for s in added:
        key = s.replace('\\n', '\n').replace('\\"', '"')
        miss = []
        for c, d in sorted(cats.items()):
            v = d.get(s, d.get(key))
            if v is None or v == s or v == key:
                if s not in keep:
                    miss.append(c)
        for c in miss:
            lack[c] += 1
        rows.append((s, miss))
    out = ['# New user-visible strings in 3.0 (for the translation pass)', '',
           'Generated by `tools/release/gen_i18n_new.py` from `%s` against `%s`. Do not translate yet: the text is frozen only when 3.0 is closed; run the script again then.' % (a.base, a.since), '',
           '%d strings are new since %s (%d used now, %d then). Catalogs: %s.' % (len(added), a.since, len(new), len(old), ', '.join(sorted(cats))), '',
           'How to translate: see docs/I18N.md. Keep `%s`, `%d`, `\\n` and acronyms; a key with a `##id` suffix keeps the suffix. Add the entries to every catalog and list machine-made ones in `app/i18n/unreviewed/<code>.txt`.', '',
           'Strings still missing a translation, per catalog (a string equal to its English key counts as missing unless it is in tools/i18n_keep_english.txt):', '']
    out.append('| Catalog | Missing of the new strings |')
    out.append('|---|---|')
    for c in sorted(cats):
        out.append('| %s | %d |' % (c, lack[c]))
    out += ['', '## The strings', '', 'Column "Missing in" shows the catalogs that lack it ("all" = every catalog).', '', '| String | Missing in |', '|---|---|']
    for s, miss in rows:
        m = 'all' if len(miss) == len(cats) and cats else (', '.join(miss) if miss else '-')
        out.append('| `%s` | %s |' % (s.replace('|', '\\|').replace('`', "'"), m))
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print('wrote', a.out, len(added), 'new strings')

if __name__ == '__main__':
    main()
