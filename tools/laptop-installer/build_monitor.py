#!/usr/bin/env python3
"""Builds OnAir-Monitor.cmd (CRLF, ASCII only) from monitor/monitor.py.

Same pattern as build.py: a batch header plus the Python script as plain text after a marker line. The batch part
cuts the script out of itself into %LOCALAPPDATA%\\OnAir\\onair-monitor.py and runs it inside Ubuntu:
    wsl.exe -d Ubuntu-24.04 -u onair -e python3 /mnt/c/.../onair-monitor.py --prefer-installed [args]
--prefer-installed runs ~/onair-monitor/monitor.py instead when the jobs installed a newer version, and otherwise
installs this copy there. The file holds no token and no secret. Arguments are passed on (for example --ascii).
"""
import pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent

HEADER = r'''@echo off
rem OnAir Monitor: a live view of what the OnAir laptop worker is building and testing.
rem Double-click this file. Keys: q quit, l log lines, h history. "OnAir-Monitor.cmd --ascii" for plain characters.
rem Generated by tools/laptop-installer/build_monitor.py from monitor/monitor.py. No token, no secret inside.
setlocal DisableDelayedExpansion
title OnAir Monitor
chcp 65001 >nul
if not defined WT_SESSION mode con: cols=120 lines=40
set "ONAIR_SELF=%~f0"
set "ONAIR_ARGS=%*"
powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "$t=[IO.File]::ReadAllText($env:ONAIR_SELF);$m='#'+'#PY-START#'+'#';$i=$t.LastIndexOf($m);if($i -lt 0){Write-Host 'The file is damaged (script part missing). Download it again.';exit 9};$s=$t.Substring($i+$m.Length).Replace([string][char]13,'').TrimStart([char]10);$d=Join-Path $env:LOCALAPPDATA 'OnAir';New-Item -ItemType Directory -Force -Path $d | Out-Null;$p=Join-Path $d 'onair-monitor.py';[IO.File]::WriteAllText($p,$s,(New-Object Text.UTF8Encoding $false));$w='/mnt/'+$p.Substring(0,1).ToLower()+$p.Substring(2).Replace([string][char]92,'/');$a=@();if($env:ONAIR_ARGS){$a=@($env:ONAIR_ARGS.Split(' ') | Where-Object {$_})};& wsl.exe -d Ubuntu-24.04 -u onair -e python3 $w --prefer-installed @a;exit $LASTEXITCODE"
set "RC=%ERRORLEVEL%"
if not "%RC%"=="0" (
  echo.
  echo   The monitor stopped with code %RC%. Is Ubuntu-24.04 installed? Run OnAir-Laptop-Setup.cmd first.
  echo   Press any key to close.
  pause >nul
)
exit /b %RC%
##PY-START##
'''


def main():
    body = (here / 'monitor' / 'monitor.py').read_text(encoding='ascii').replace('\r\n', '\n')
    text = (HEADER + body).replace('\r\n', '\n').replace('\n', '\r\n')
    data = text.encode('ascii')  # fails loudly on any non-ASCII character
    if re.search(rb'(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_|RUNNER_TOKEN|-----BEGIN)', data):
        sys.exit('refusing to write: something that looks like a token is in the monitor sources')
    out = here / 'OnAir-Monitor.cmd'
    out.write_bytes(data)
    print('wrote', out.name, len(data), 'bytes')


if __name__ == '__main__':
    main()
