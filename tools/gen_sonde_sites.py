#!/usr/bin/env python3
"""Generate core/src/sonde/sonde_sites_known.cpp, the built-in list of radiosonde launch sites, from the station list of the
Integrated Global Radiosonde Archive version 2 (IGRA 2, NOAA National Centers for Environmental Information, a US Government work in the
public domain): https://www.ncei.noaa.gov/data/integrated-global-radiosonde-archive/doc/igra2-station-list.txt
Durre, I., X. Yin, R. S. Vose, S. Applequist and J. Arnfield, 2016: Integrated Global Radiosonde Archive (IGRA), Version 2. NOAA NCEI.
doi:10.7289/V5X63K0Q.
Kept: the stations with soundings in the archive in MIN_YEAR or later (the ones still launching). Fixed columns as in igra2-readme.txt.
Usage (from the repository root): python3 tools/gen_sonde_sites.py igra2-station-list.txt"""
import os, sys

MIN_YEAR = 2025
KEEP_UPPER = {"AFB", "AP", "AWS", "NWS", "WSO", "WFO", "NWSO", "WSMO", "UA", "RAAF", "RAF", "USAF", "DWD", "II", "III", "IV", "AMO", "MO", "BMO", "CRS", "AB", "NAS", "NAF", "IAP", "AG", "AES"}

def nice(name):
    out = []
    for w in name.split(" "):
        if not w: continue
        if w.strip("()").upper() in KEEP_UPPER: out.append(w); continue
        s, up = "", True
        for ch in w:
            s += ch.upper() if up else ch.lower()
            up = not ch.isalpha() and ch != "'"
        out.append(s)
    return " ".join(out)

def main():
    src = sys.argv[1]
    rows = []
    with open(src, encoding="latin-1") as f:
        for l in f:
            try:
                sid = l[0:11].strip(); lat = float(l[12:20]); lon = float(l[21:30]); elev = float(l[31:37])
                name = l[41:71].strip(); last = int(l[77:81])
            except ValueError:
                continue
            if last < MIN_YEAR or abs(lat) > 90 or abs(lon) > 180 or not name: continue
            wmo = int(sid[6:]) if sid[2] == "M" and sid[6:].isdigit() else 0
            rows.append((sid, wmo, lat, lon, elev if elev > -998 else 0.0, nice(name)))
    rows.sort(key=lambda r: r[0])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "core/src/sonde/sonde_sites_known.cpp"), "w", encoding="utf-8") as o:
        o.write("// Generated by tools/gen_sonde_sites.py from the IGRA 2 station list (NOAA NCEI, public domain; see sonde_sites_known.h). Do not edit by hand.\n")
        o.write("// %d stations with soundings in %d or later.\n" % (len(rows), MIN_YEAR))
        o.write('#include "dect2/sonde/sonde_sites_known.h"\n\nnamespace dect2 {\n\nnamespace {\nconst KnownSondeSite kSites[] = {\n')
        for sid, wmo, lat, lon, elev, name in rows:
            o.write('    {"%s", %d, %.4f, %.4f, %.0f, "%s"},\n' % (sid, wmo, lat, lon, elev, name.replace("\\", "\\\\").replace('"', '\\"')))
        o.write("};\n}  // namespace\n\n")
        o.write("const KnownSondeSite* builtinSondeSites(size_t& n) { n = sizeof kSites / sizeof kSites[0]; return kSites; }\n\n}  // namespace dect2\n")
    print("%d sites" % len(rows))

main()
