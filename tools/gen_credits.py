#!/usr/bin/env python3
"""Generate the credits from tools/credits_data.tsv (the one place to edit):
   app/panels/credits_data.h  - the table of the in-app Credits window
   THIRD_PARTY.md             - the audit, the table and the notices
   docs/credits-for-website.md - the same list, to paste into the website and the wiki
Run from the repository root: python3 tools/gen_credits.py"""
import csv, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
with open(os.path.join(root, "tools/credits_data.tsv"), encoding="utf-8") as f:
    for line in f:
        line = line.rstrip("\n")
        if not line or line.startswith("#"): continue
        c = line.split("\t")
        if len(c) != 7 or any(not x.strip() for x in c):
            sys.exit("bad row: " + line[:60])
        rows.append([x.strip() for x in c])

def cs(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

with open(os.path.join(root, "app/panels/credits_data.h"), "w", encoding="utf-8") as o:
    o.write("// Generated by tools/gen_credits.py from tools/credits_data.tsv. Do not edit by hand.\n#pragma once\n\n"
            "struct CreditEntry { const char *name, *author, *licence, *where, *how, *url, *note; };\n\n"
            "inline constexpr CreditEntry kCredits[] = {\n")
    for r in rows: o.write("    {" + ", ".join(cs(x) for x in r) + "},\n")
    o.write("};\ninline constexpr int kCreditCount = (int)(sizeof kCredits / sizeof kCredits[0]);\n")

def table(cols):
    h = ["Name", "Author", "Licence", "Where used", "How", "Link", "What it needs / status"]
    out = ["| " + " | ".join(h[i] for i in cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for i in cols:
            x = r[i].replace("|", "/")
            cells.append("<" + x + ">" if i == 5 else x)
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)

