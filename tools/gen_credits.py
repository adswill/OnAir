def refs_md(refs):
    out = []
    for t in [x.strip() for x in refs.split(",")]:
        if t.startswith("#"): out.append("[%s](https://github.com/adswill/OnAir/issues/%s)" % (t, t[1:]))
        elif t.startswith("commit:"): out.append("[%s](https://github.com/adswill/OnAir/commit/%s)" % (t[7:], t[7:]))
        else: out.append("Discord")
    return ", ".join(out)
def who_md(r): return "[%s](%s)" % (r[0], r[1]) if r[1] != "-" else r[0]
people = {}
for r in crow: people.setdefault(r[0], []).append(r)
bymode = {}
for r in crow:
    for m in r[4].split(";"):
        m = m.strip()
        if not m.startswith("area:"): bymode.setdefault(m, set()).add(r[0])
byarea = {}
for r in crow:
    for m in r[4].split(";"):
        m = m.strip()
        if m.startswith("area:"): byarea.setdefault(m[5:], set()).add(r[0])
CIN = ("OnAir exists because of the people below: they sent fixes, reported bugs, shared recordings, translated and suggested ideas. "
       "The maintainer, [Kristijonas Adomaitis](https://github.com/adswill), is the author and is not repeated here. "
       "Only names people already use in public are shown. **Want your name changed or removed? Tell us on Discord or open an issue.**\n")
def contrib_md():
    t = ["## People (%d)\n" % len(people)]
    t.append("| Who | What | Kind | Where | Reference |\n|---|---|---|---|---|")
    for n in sorted(people, key=str.lower):
        for r in people[n]:
            t.append("| %s | %s | %s | %s | %s |" % (who_md(r), r[3].replace("|", "/"), r[2], r[4].replace("area:", ""), refs_md(r[5])))
    t.append("\n## By mode\n")
    for m in sorted(bymode): t.append("- **%s**: %s" % (m, ", ".join(sorted(bymode[m], key=str.lower))))
    t.append("\n## By area\n")
    for m in sorted(byarea): t.append("- **%s**: %s" % (m, ", ".join(sorted(byarea[m], key=str.lower))))
    return "\n".join(t) + "\n"
