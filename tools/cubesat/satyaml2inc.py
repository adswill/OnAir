# Converts gr-satellites satyaml files (GPL-3.0-or-later, Daniel Estevez EA4GPZ and contributors) into a C++ table (rows) for OnAir.
import sys, os, re
def parse(path):
    lines = []
    for raw in open(path, encoding='utf-8'):
        s = raw.rstrip('\n')
        if not s.strip() or s.lstrip().startswith('#'): continue
        ind = len(s) - len(s.lstrip(' '))
        lines.append((ind, s.strip()))
    root = {}
    stack = [(-1, root)]
    anchors = {}
    for i, (ind, t) in enumerate(lines):
        while stack and stack[-1][0] >= ind: stack.pop()
        parent = stack[-1][1]
        if t.startswith('- '):
            v = t[2:].strip()
            if isinstance(parent, dict):
                # list under the last key
                k = parent.get('__lastkey')
                if not isinstance(parent.get(k), list): parent[k] = []
                parent[k].append(anchors.get(v[1:], v) if v.startswith('*') else v)
            continue
        m = re.match(r'^(&(\S+)\s+)?([^:]+):\s*(.*)$', t)
        if not m:
            # a bare value (e.g. 'unknown') under an anchor key
            if isinstance(parent, dict): parent['__value'] = t
            continue
        anc, key, val = m.group(2), m.group(3).strip(), m.group(4).strip()
        if isinstance(parent, dict): parent['__lastkey'] = key
        if val == '':
            d = {}
            parent[key] = d
            stack.append((ind, d))
            if anc: anchors[anc] = d
        else:
            parent[key] = val
    return root
FR = {'AX.25 G3RUH':'G3ruh','AX.25':'Ax25','AX100 ASM+Golay':'Ax100M5','AX100 Reed Solomon':'Ax100M6','USP':'Usp','U482C':'U482c',
      'CCSDS Concatenated':'CcsdsConcat','CCSDS Reed-Solomon':'CcsdsRs','AO-40 FEC':'Ao40','Mobitex':'Mobitex','Mobitex-NX':'MobitexNx',
      'BEESAT-1':'Beesat1','BEESAT-9':'Beesat9','NGHam':'Ngham','NGHam no Reed Solomon':'NghamNoRs'}
rows = []
d = sys.argv[1]
for fn in sorted(os.listdir(d)):
    if not fn.endswith('.yml'): continue
    y = parse(os.path.join(d, fn))
    try: norad = int(y.get('norad', '0'))
    except ValueError: norad = 0
    name = y.get('name', fn[:-4])
    for tname, tx in (y.get('transmitters') or {}).items():
        if not isinstance(tx, dict) or tname.startswith('__'): continue
        fr = tx.get('framing', '').strip()
        try: hz = int(round(float(tx.get('frequency', '0'))))
        except ValueError: hz = 0
        try: baud = int(round(float(tx.get('baudrate', '0'))))
        except ValueError: baud = 0
        tel = []
        for e in tx.get('data', []) or []:
            if isinstance(e, dict) and 'telemetry' in e: tel.append(e['telemetry'])
        def num(k, dflt=0):
            try: return int(round(float(tx.get(k, dflt))))
            except ValueError: return dflt
        flags = []
        if tx.get('precoding', '').strip() == 'differential': flags.append('kGrDiff')
        if tx.get('RS basis', '').strip() == 'conventional': flags.append('kGrRsConv')
        cv = tx.get('convolutional', '').strip()
        if cv == 'NASA-DSN': flags.append('kGrNasaDsn')
        elif cv == 'CCSDS uninverted': flags.append('kGrUninverted')
        elif cv == 'NASA-DSN uninverted': flags.append('kGrNasaDsn | kGrUninverted')
        if tx.get('scrambler', '').strip() == 'none': flags.append('kGrNoScrambler')
        rows.append((norad, name, tname, hz, tx.get('modulation', '').strip(), baud, FR.get(fr, 'Other'), fr, '+'.join(tel), num('deviation'),
                     num('af_carrier'), num('frame size'), num('RS interleaving', 1), ' | '.join(flags) or '0', tx.get('callsign', '').strip()))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// Generated by tools/satyaml2inc.py from gr-satellites python/satyaml (GPL-3.0-or-later, Daniel Estevez EA4GPZ and contributors),',
       '// commit ' + sys.argv[2] + '. Do not edit: regenerate. Columns: NORAD, satellite, transmitter, Hz, modulation, baud, framing, gr-satellites',
       '// framing name, telemetry decoder, deviation Hz, AF carrier Hz, frame size, RS interleaving, flags, callsign.']
for r in rows:
    out.append('{%d, %s, %s, %d, %s, %d, GrFraming::%s, %s, %s, %d, %d, %d, %d, %s, %s},' % (r[0], q(r[1]), q(r[2]), r[3], q(r[4]), r[5], r[6], q(r[7]), q(r[8]), r[9], r[10], r[11], r[12], r[13], q(r[14])))
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
print(len(rows), 'rows')
from collections import Counter
print(Counter(r[6] for r in rows).most_common())
