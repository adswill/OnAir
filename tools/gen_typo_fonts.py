"""Embeds third_party/fonts/*.ttf into app/ui/typo_fonts.inc as raw-deflate byte arrays (inflated at start-up by dect2::inflateRaw)."""
import os, zlib, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = ["Inter-Regular", "Inter-Medium", "Inter-SemiBold", "JetBrainsMono-Regular", "JetBrainsMono-Bold"]
out = ["// Generated by tools/gen_typo_fonts.py from third_party/fonts (SIL OFL 1.1, see third_party/fonts/README.md). Do not edit.\n"]
for n in names:
    raw = open(os.path.join(root, "third_party/fonts", n + ".ttf"), "rb").read()
    c = zlib.compressobj(9, zlib.DEFLATED, -15); z = c.compress(raw) + c.flush()
    ident = n.replace("-", "_")
    out.append("static const unsigned kFont_%s_raw = %d;\nstatic const unsigned char kFont_%s[] = {\n" % (ident, len(raw), ident))
    for i in range(0, len(z), 24): out.append(",".join(str(b) for b in z[i:i+24]) + ",\n")
    out.append("};\n")
open(os.path.join(root, "app/ui/typo_fonts.inc"), "w").write("".join(out))
