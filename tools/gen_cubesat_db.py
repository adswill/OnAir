#!/usr/bin/env python3
"""Builds core/src/cubesat/cubesat_db_data.inc: the transmitter table and a TLE snapshot of the Smart CubeSat decoder.
Data: SatNOGS DB (https://db.satnogs.org, CC-BY-SA 4.0, credit SatNOGS DB contributors) and CelesTrak TLEs (T.S. Kelso).
Usage: tools/gen_cubesat_db.py [dir with tx.json sats.json active.txt amateur.txt cubesat.txt]   (fetches them when the dir is missing)
Only VHF / UHF (130 - 480 MHz) transmitters of satellites in orbit that are alive and active, with a modulation the decoder knows."""
import json, os, sys, urllib.request

d = sys.argv[1] if len(sys.argv) > 1 else "."
def get(name, url):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        os.makedirs(d, exist_ok=True)
        urllib.request.urlretrieve(url, p)
    return p
tx = json.load(open(get("tx.json", "https://db.satnogs.org/api/transmitters/?format=json")))
sats = {s["sat_id"]: s for s in json.load(open(get("sats.json", "https://db.satnogs.org/api/satellites/?format=json")))}
def tles(p):
    L = open(p).read().replace("\r", "").split("\n"); r = {}
    for i in range(len(L) - 2):
        if L[i + 1].startswith("1 ") and L[i + 2].startswith("2 "): r[int(L[i + 1][2:7])] = (L[i].strip(), L[i + 1].strip(), L[i + 2].strip())
    return r
T = {}
for n, g in (("active.txt", "active"), ("amateur.txt", "amateur"), ("cubesat.txt", "cubesat")):
    T.update(tles(get(n, "https://celestrak.org/NORAD/elements/gp.php?GROUP=%s&FORMAT=tle" % g)))

# SatNOGS mode -> (modulation kind, framing hint)
MOD = {"CW": (1, 0), "AFSK": (2, 1), "AFSK TUBiX10": (2, 5), "FSK": (3, 0), "GFSK": (3, 0), "GMSK": (3, 0), "MSK": (3, 0),
       "FSK AX.100 Mode 5": (3, 2), "MSK AX.100 Mode 5": (3, 2), "FSK AX.25 G3RUH": (3, 3), "GMSK USP": (3, 4), "DOKA": (3, 6),
       "BPSK": (4, 0), "DBPSK": (4, 0), "LoRa": (5, 0)}
rows, used = [], set()
seen = set()
for t in tx:
    if not (t.get("alive") and t.get("status") == "active" and t.get("type") == "Transmitter" and t.get("downlink_low")): continue
    if t["mode"] not in MOD or not (130e6 <= t["downlink_low"] <= 480e6): continue
    s = sats.get(t["sat_id"])
    if not s or s["status"] != "in orbit" or t["norad_cat_id"] not in T: continue
    mod, fr = MOD[t["mode"]]
    baud = int(t["baud"] or 0)
    f = int(t["downlink_low"])
    key = (t["norad_cat_id"], round(f / 2500), mod, baud)
    if key in seen: continue
    seen.add(key)
    desc = (t.get("description") or "").replace('"', "'").replace("\\", " ")[:34]
    name = s["name"].replace('"', "'")
    rows.append((t["norad_cat_id"], name, f, mod, fr, baud, desc, t["mode"]))
    used.add(t["norad_cat_id"])
rows.sort()
out = ["// Generated by tools/gen_cubesat_db.py (do not edit): SatNOGS DB transmitters (CC-BY-SA 4.0, SatNOGS DB contributors) and CelesTrak TLEs,",
       "// snapshot of %s. A starting point: the app refreshes TLEs from CelesTrak and the user can edit the table." % __import__("time").strftime("%Y-%m-%d", __import__("time").gmtime()),
       "// { norad, name, downlink Hz, modulation kind, framing hint, baud (0 = unknown), description, SatNOGS mode }"]
out.append("static const CsTxRow kCsTx[] = {")
for r in rows: out.append('{%d,"%s",%d,%d,%d,%d,"%s","%s"},' % r)
out.append("};")
out.append("static const CsTleRow kCsTle[] = {")
for n in sorted(used):
    nm, a, b = T[n]
    out.append('{%d,"%s","%s","%s"},' % (n, nm.replace('"', "'"), a, b))
out.append("};")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "src", "cubesat", "cubesat_db_data.inc"), "w").write("\n".join(out) + "\n")
print(len(rows), "transmitters,", len(used), "satellites")
