# Builds core/src/bgan/bgan_tables_data.inc from the forward-bearer tables published with ETSI TS 102 744-2-1 (the archive
# ts_1027440201v010101p0.zip: Annex C.1 turbo interleavers *_TCI.TXT, Annex C.2 puncturing / channel interleaving / symbol mapping *_CIPM.TXT).
# Usage: tools/bgan_tables.py <dir with the unpacked AnnexC1 and AnnexC2 folders> <output .inc>
# Each table is delta coded (mod its largest index + 1, 16 bits) and the whole blob is raw-deflate compressed.
import re, struct, sys, zlib
from pathlib import Path

base, out = Path(sys.argv[1]), Path(sys.argv[2])
c1, c2 = base / 'ts_1027440201_AnnexC1_v010101p0', base / 'ts_1027440201_AnnexC2_v010101p0'
FAM = ['F80T025Q', 'F80T1Q', 'F80T1X', 'F80T45X', 'FR80T25X4', 'FR80T25X16', 'FR80T25X32', 'FR80T25X64', 'FR80T5X4', 'FR80T5X16', 'FR80T5X32', 'FR80T5X64']
SUB = ['L8', 'L7', 'L6', 'L5', 'L4', 'L3', 'L2', 'L1', 'RE', 'H1', 'H2', 'H3', 'H4', 'H5', 'H6']

def rows(path):
    res = []
    for l in path.read_text(errors='replace').splitlines():
        p = re.findall(r'-?\d+', l)
        if l.strip() and l.split()[0].isdigit() and len(p) >= 2 and not l.strip().startswith(('NOTE', 'User')):
            res.append([int(x) for x in p])
    return res

blob = bytearray()
index = []
for fi, fam in enumerate(FAM):
    for si, sub in enumerate(SUB):
        cipm = c2 / f'{fam}{sub}_CIPM.TXT'
        tci = c1 / f'{fam}{sub}_TCI.TXT'
        if not cipm.exists():
            cipm = c2 / f'{fam}{sub}_4B_CIPM.TXT'
            tci = c1 / f'{fam}{sub}_4B_TCI.TXT'
        if not cipm.exists() or not tci.exists():
            continue
        t = rows(tci)
        c = rows(cipm)
        N = len(t)
        assert [r[0] for r in t] == list(range(N)), tci
        perm = [r[1] for r in t]
        assert sorted(perm) == list(range(N)), tci
        bps = len(c[0]) - 1
        assert bps in (2, 4, 5, 6) and [r[0] for r in c] == list(range(len(c))) and all(len(r) == bps + 1 for r in c), cipm
        mp = [x for r in c for x in r[1:]]
        assert max(mp) < 3 * N, cipm
        M = 3 * N
        o = len(blob)
        prev = 0
        for v in perm:
            blob += struct.pack('<H', (v - prev) % N); prev = v
        prev = 0
        for v in mp:
            blob += struct.pack('<H', (v - prev) % M); prev = v
        index.append((fi, si, N, len(c), bps, o))

z = zlib.compressobj(9, zlib.DEFLATED, -15)
comp = z.compress(bytes(blob)) + z.flush()
with out.open('w') as f:
    f.write('// Generated by tools/bgan_tables.py from the tables published with ETSI TS 102 744-2-1 (Annexes C.1 and C.2). Do not edit.\n')
    f.write(f'static const size_t kBganBlobRaw = {len(blob)};\n')
    f.write('static const BganTableIndex kBganIndex[] = {\n')
    for r in index:
        f.write('{%d,%d,%d,%d,%d,%d},\n' % r)
    f.write('};\nstatic const unsigned char kBganBlob[] = {\n')
    for i in range(0, len(comp), 32):
        f.write(','.join(str(b) for b in comp[i:i + 32]) + ',\n')
    f.write('};\n')
print(len(index), 'tables', len(blob), 'raw bytes', len(comp), 'deflated')
