# Regenerates core/src/dsp/vulkan/ldpc_spirv.h (the SPIR-V of the Vulkan LDPC kernels) from the GLSL next to it.
# The build never needs a shader compiler: the generated header is committed. Run this after changing a .comp file, on any machine with
# glslangValidator (Debian/Ubuntu: apt install glslang-tools spirv-tools; macOS: brew install glslang spirv-tools), then commit both.
#   tools/gen_vulkan_spirv.sh
set -eu
cd "$(dirname "$0")/.."
D=core/src/dsp/vulkan
OUT=$D/ldpc_spirv.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
for s in ldpc_t2 ldpc_qc; do
    glslangValidator -V --target-env vulkan1.0 -Os --vn "k_${s}_spv" -o "$TMP/$s.h" "$D/$s.comp" >/dev/null
    glslangValidator -V --target-env vulkan1.0 -Os -o "$TMP/$s.spv" "$D/$s.comp" >/dev/null
    if command -v spirv-val >/dev/null 2>&1; then spirv-val --target-env vulkan1.0 "$TMP/$s.spv"; fi
done
{
    echo "// Generated by tools/gen_vulkan_spirv.sh from ldpc_t2.comp and ldpc_qc.comp ($(glslangValidator --version | head -1 | sed 's/^Glslang Version: *//'))."
    echo "// Do not edit: change the .comp files and run the script again."
    echo "#pragma once"
    echo "#include <cstdint>"
    for s in ldpc_t2 ldpc_qc; do
        # glslang writes "const uint32_t k_..._spv[] = {...};" after a comment banner
        sed -n '/^const uint32_t/,$p' "$TMP/$s.h" | sed 's/^const uint32_t/static const uint32_t/'
    done
} > "$OUT"
echo "wrote $OUT"
