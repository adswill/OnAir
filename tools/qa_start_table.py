"""tests/qa/qa_start.inc from the QA sweep's CI timing logs (docs/CI-FAST.md (4.7)).

test_qa_sweep tries each mode with 3 s, 8 s, 32 s of signal and then 32 s at real time, every condition again on each try, and keeps
only the last try. A mode that always ends on a later try spent most of its time on tries whose results were thrown away (2026-11-27:
the 71 modes that needed three or four tries were 62 % of the sweep's time). The table names, per mode, the try it ended on in CI; the
sweep starts there, and goes on to the longer tries as before when that one is not enough. Modes not in the table start at the first try.
  tools/qa_start_table.py qatime.log [more logs...] > tests/qa/qa_start.inc
qatime.log lines (QA_TIMING_LOG): id, wall seconds, tries, seconds of the last try, paced (0/1), clean verdict.
"""
import sys

def main():
    last = {}
    for path in sys.argv[1:]:
        for line in open(path, errors="replace"):
            f = line.rstrip("\n").split("\t")
            if len(f) < 6: continue
            try: tries = int(f[2])
            except ValueError: continue
            last[f[0]] = max(last.get(f[0], 0), tries - 1)   # the index of the last try; several logs: the latest start that was needed
    print("// Generated by tools/qa_start_table.py from the QA sweep's CI timing logs: the try each mode ended on (0 = 3 s, 1 = 8 s, 2 = 32 s,")
    print("// 3 = 32 s at real time). test_qa_sweep starts there (QA_FROM_START=1: from the first try). Modes at 0 are left out.")
    for k in sorted(last):
        if last[k] > 0:
            print('{"%s", %d},' % (k, last[k]))

if __name__ == "__main__":
    main()
