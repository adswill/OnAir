"""Generates core/src/mesh/mesh_presets_data.cpp (the built-in MeshCore radio presets) from the meshcore.nz API.

  python3 tools/gen_meshcore_presets.py                 fetch https://api.meshcore.nz/api/v1/config and write the table
  python3 tools/gen_meshcore_presets.py --json f.json   use a saved copy (offline)
The table is committed, so builds need no network. The regions are worked out from the preset title (the API has no region field);
core/src/mesh/mesh_presets.cpp has the same rule (meshCoreRegionOf) and tests/mesh/test_mesh_presets_meshcore.cpp checks the two agree."""
import argparse, datetime, json, os, sys, urllib.request

URL = "https://api.meshcore.nz/api/v1/config"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "src", "mesh", "mesh_presets_data.cpp")

def region_of(title):
    t = title.lower()
    for key, reg in (("australia", "Oceania"), ("new zealand", "Oceania"), ("brazil", "South America"), ("canada", "North America"),
                     ("usa", "North America"), ("costa rica", "North America"), ("vietnam", "Asia")):
        if key in t: return reg
    return "Europe"

def parse(doc):
    """The preset entries of the API document: (title, region, mhz, bw_khz, sf, cr, note)."""
    rows = []
    for e in doc["config"]["suggested_radio_settings"]["entries"]:
        note = ""
        for part in e.get("description", "").split("/"):
            p = part.strip()
            if len(p) == 2 and p[0].isdigit() and p[1] == "B": note = p
        rows.append((e["title"], region_of(e["title"]), float(e["frequency"]), float(e["bandwidth"]), int(e["spreading_factor"]), int(e["coding_rate"]), note))
    return rows

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json"); ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    if a.json: raw = open(a.json, "rb").read()
    else: raw = urllib.request.urlopen(urllib.request.Request(URL, headers={"User-Agent": "OnAir-presets-generator"}), timeout=30).read()
    rows = parse(json.loads(raw))
    if not rows: sys.exit("no preset entries in the document")
    now = datetime.datetime.now(datetime.timezone.utc)
    with open(a.out, "w") as f:
        f.write("// Generated by tools/gen_meshcore_presets.py from %s, fetched %s. Do not edit; run the script to refresh.\n" % (URL, now.strftime("%Y-%m-%d")))
        f.write('#include "dect2/mesh/mesh_presets.h"\n\nnamespace dect2 {\n\n')
        f.write("const long long kMeshCorePresetsFetched = %dLL;   // Unix time\n" % int(now.timestamp()))
        f.write("const MeshCorePreset kMeshCorePresets[] = {\n")
        for t, r, m, b, s, c, n in rows:
            f.write('    {"%s", "%s", %.3f, %g, %d, %d, "%s"},\n' % (t, r, m, b, s, c, n))
        f.write("};\nconst int kMeshCorePresetCount = %d;\n\n} // namespace dect2\n" % len(rows))
    print("%d presets -> %s" % (len(rows), a.out))

if __name__ == "__main__": main()
