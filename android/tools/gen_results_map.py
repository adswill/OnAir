"""Generates native/src/results_generic_map.inc: for every standard in modeSummary() (core/src/engine/modes.cpp) that has no hand-written exporter
in results_json.cpp, code that turns the mode's telemetry struct (fields read from the core's headers) into cards and tables with the field names,
newest list items first. So a new mode's decoded lists reach the phone with no Android change. Only plain fields are used: strings, numbers,
vectors/deques/lists of plain structs or strings. Runs from tools/build_native.sh; CI checks that the committed file is current."""
import glob, os, re, sys
_android = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
repo = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(_android)
SCALAR = {'int', 'unsigned', 'long', 'short', 'float', 'double', 'bool', 'char', 'int8_t', 'int16_t', 'int32_t', 'int64_t', 'uint8_t', 'uint16_t', 'uint32_t', 'uint64_t',
          'unsigned int', 'unsigned char', 'unsigned long', 'unsigned short', 'long long', 'unsigned long long', 'size_t'}
MAX_CARDS, MAX_COLS, MAX_TABLES, MAX_ROWS = 12, 8, 4, 80

def strip_comments(s): return re.sub(r'/\*.*?\*/', '', re.sub(r'//[^\n]*', '', s), flags=re.S)
def bodies(text):
    # every "struct Name { ... };" with brace matching; a name may be repeated in several headers (the first with fields is used)
    out = {}
    for m in re.finditer(r'\bstruct\s+(\w+)(?:\s+final)?\s*\{', text):
        i, depth = m.end(), 1
        while i < len(text) and depth:
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        out.setdefault(m.group(1), text[m.end():i - 1])
    return out
def fields(body):
    # top-level statements only: nested braces (member functions, nested types, brace initialisers) are removed first
    flat, depth = '', 0
    for ch in body:
        if ch == '{': depth += 1; continue
        if ch == '}': depth -= 1; continue
        if depth == 0: flat += ch
    out = []
    for st in flat.split(';'):
        st = ' '.join(st.split())
        if not st or '(' in st or '[' in st or re.match(r'(static|using|typedef|friend|enum|struct|class|template|public|private|protected)\b', st): continue
        st = re.sub(r'^(const|mutable)\s+', '', st)
        m = re.match(r'((?:std::(?:vector|deque|list)<[\w:, ]+>)|[A-Za-z_][\w:]*(?: (?:int|char|long|short))*)\s+(\w.*)$', st)
        if not m: continue
        typ, rest = m.group(1).strip(), m.group(2)
        if '<' in typ and ',' in typ: continue             # an allocator or a pair: not a plain list
        for d in rest.split(','):
            n = re.match(r'\s*(\w+)\s*(=.*)?$', d)
            if n: out.append((typ, n.group(1)))
    return out

defs = {}      # name -> [(header, body)]: the same name exists in several namespaces (Station, Message ...)
for h in sorted(glob.glob(os.path.join(repo, 'core/include/dect2/**/*.h'), recursive=True)):
    for k, v in bodies(strip_comments(open(h, encoding='utf-8', errors='ignore').read())).items():
        defs.setdefault(k, []).append((h, v))
def find(name, owner=None):
    # (header, body) of a struct: the only one of that name, else the one next to the struct that uses it; None when unclear (the field is skipped)
    c = defs.get(name.split('::')[-1], [])
    if not c: return None
    if len(c) == 1: return c[0]
    if owner:
        same = [x for x in c if x[0] == owner] or [x for x in c if os.path.dirname(x[0]) == os.path.dirname(owner)]
        if len(same) == 1: return same[0]
    return None

def is_scalar(t): return t in SCALAR or t.split('::')[-1] in SCALAR
def is_string(t): return t == 'std::string'
def label(n):
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1 \2', n).replace('_', ' ').strip()
    return s[:1].upper() + s[1:]
def elem_of(t):
    m = re.fullmatch(r'std::(?:vector|deque|list)<\s*([\w:]+(?: (?:int|char))?)\s*>', t)
    return m.group(1) if m else None

src = open(os.path.join(repo, 'core/src/engine/modes.cpp'), encoding='utf-8').read()
s = src.index('std::string modeSummary(const RxTelemetry& t) {')
pairs = {}
for line in src[s:src.index('\n}\n', s)].splitlines():
    m = re.match(r'\s*((?:case \d+:\s*)+)return \w+\(t\.(\w+)\);', line)
    if m:
        for n in re.findall(r'case (\d+):', m.group(1)): pairs[int(n)] = m.group(2)
# the standards results_json.cpp handles itself (its switch in resultsJson)
own = open(os.path.join(_android, 'native/src/results_json.cpp'), encoding='utf-8').read()
own = set(int(x) for x in re.findall(r'\bcase (\d+):', own[own.index('std::string resultsJson('):]))
rx_members = dict((n, t) for t, n in fields(find('RxTelemetry')[1]))
SKIP_CARD = {'seq', 'state', 'version', 'generation'}

out = ['// Generated by tools/gen_results_map.py from the telemetry structs in core/include. Do not edit.']
done = cards = tables = 0
for std in sorted(pairs):
    if std in own: continue
    m = pairs[std]
    typ = rx_members.get(m)
    top = find(typ or '', os.path.join(repo, 'core/include/dect2/t2/t2rx.h'))
    if not top: continue
    fs = fields(top[1])
    if not fs: continue
    lines, nc, nt = [], 0, 0
    for t, n in fs:
        if nc < MAX_CARDS and n not in SKIP_CARD and (is_string(t) or (is_scalar(t) and t != 'bool')):
            lines.append(f'    cardIf(o, "{label(n)}", t.{n});'); nc += 1
    for t, n in fs:
        e = elem_of(t)
        if not e or nt >= MAX_TABLES: continue
        if is_string(e): cols = [('Item', None)]
        else:
            d = find(e, top[0])
            if not d: continue
            ef = fields(d[1])
            strs = [x for x in ef if is_string(x[0])]
            nums = [x for x in ef if is_scalar(x[0]) and x[0] != 'bool']
            picked = (strs + nums)[:MAX_COLS]
            cols = [(label(x[1]), x[1]) for x in ef if x in picked]
            if not any(is_string(x[0]) for x in ef) and len(cols) < 2: continue   # plain sample or level lists are plots, not lists to read
        head = ', '.join('"%s"' % c[0] for c in cols)
        cells = ', '.join('cell(e)' if c[1] is None else f'cell(e.{c[1]})' for c in cols)
        lines.append(f'    {{ Table tb({{{head}}}); int n = 0; for (auto it = t.{n}.rbegin(); it != t.{n}.rend() && n < {MAX_ROWS}; ++it, ++n) {{ const auto& e = *it; tb.row({{{cells}}}); }} if (n) addTable(o, "{label(n)}", tb); }}')
        nt += 1
    if not lines: continue
    done += 1; cards += nc; tables += nt
    out.append(f'case {std}: {{\n    const auto& t = rx.{m}; (void)t;\n' + '\n'.join(lines) + '\n    break;\n}')
open(os.path.join(_android, 'native/src/results_generic_map.inc'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(pairs), 'standards in modeSummary,', done, 'generated,', cards, 'cards,', tables, 'tables')
